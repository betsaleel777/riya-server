                    if ($contratExistant) {
                        $this->command->warn("⚠ Ligne {$index}: Contrat en cours déjà existant - Client: {$personne->nom_complet}, Bien: {$appartement->reference} (ignoré)");
                        $errorCount++;
                        return;
