                        'debut' => Carbon::parse($row['DATE_VISITE'])->format('Y-m-d'),
                        'commission' => $commission,
                        'montant_location' => $appartement->montant_location,
                    ]);

                    $contrat->operation()->associate($visite)->save();
                    $visite->setValide();
                    $appartement->setBusy();

